import { fetchJson, isObject, safeCredential, tokenResponse } from './provider-http';
import { ProviderError, type Credential, type ProviderAdapter } from './provider-types';

const label = 'TikTok account holder';
const api = 'https://business-api.tiktok.com/open_api/v1.3/';
const docsUrl = 'https://business-api.tiktok.com/portal/docs?id=1738083939371009';

function configured(env: NodeJS.ProcessEnv, key: string): string {
  const value = env[key]?.trim();
  if (!value || /[\r\n\0]/.test(value)) throw new ProviderError(`Configure ${key} before connecting the TikTok account holder.`, 503);
  return value;
}

function identity(value: unknown): string {
  if (typeof value !== 'string' || !value.trim() || value.length > 300 || /[\r\n\0]/.test(value)) {
    throw new ProviderError(`${label} returned an invalid account identity.`, 502);
  }
  return value;
}

function data(body: Record<string, unknown>): Record<string, unknown> {
  if (body.code !== 0) throw new ProviderError('TikTok account-holder authorization was rejected. Check TikTok Accounts approval and reconnect.', 403);
  if (!isObject(body.data)) throw new ProviderError(`${label} returned an unexpected response.`, 502);
  return body.data;
}

function checkRedirect(value: string): void {
  let url: URL | undefined;
  try { url = new URL(value); } catch { /* Report a safe, actionable configuration error. */ }
  if (!url || url.protocol !== 'https:' || url.port || /^https:\/\/[^/]+:\d+(?:\/|$)/.test(value) ||
      ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname) || url.username || url.password || url.search || url.hash || !url.pathname.endsWith('/') || value.length > 512) {
    throw new ProviderError('TikTok account-holder authorization needs a public HTTPS redirect ending in /, without a port, query, or fragment. Check your public address and registered callback.');
  }
}

/** The portal supplies a client_key that is not necessarily the numeric Business app ID. */
function authorizationUrl(env: NodeJS.ProcessEnv, redirectUri: string): URL {
  checkRedirect(redirectUri);
  let url: URL;
  try { url = new URL(configured(env, 'TIKTOK_BUSINESS_ACCOUNT_AUTH_URL')); }
  catch { throw new ProviderError('Copy the TikTok account holder authorization URL from this Business app’s Basic Information page.'); }
  const allowed = new Set(['client_key', 'scope', 'response_type', 'redirect_uri', 'state', 'disable_auto_auth']);
  if (url.origin !== 'https://www.tiktok.com' || !['/v2/auth/authorize', '/v2/auth/authorize/'].includes(url.pathname) || url.username || url.password || url.hash ||
      [...url.searchParams.keys()].some(key => !allowed.has(key) || url.searchParams.getAll(key).length !== 1) ||
      !url.searchParams.get('client_key')?.trim() || !url.searchParams.get('scope')?.trim() || url.searchParams.get('response_type') !== 'code') {
    throw new ProviderError('Use the original TikTok account holder authorization URL generated by your TikTok for Business app, without credentials or extra parameters.');
  }
  if (url.searchParams.get('redirect_uri') !== redirectUri) {
    throw new ProviderError('The TikTok account-holder authorization URL uses a different redirect. Activate the account-holder callback shown in Connector, including its final /, then copy its newly generated authorization URL.');
  }
  return url;
}

async function post(path: string, body: Record<string, string>): Promise<Record<string, unknown>> {
  return data(await fetchJson(label, `${api}${path}`, {
    method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body),
  }));
}

function appCredentials(env: NodeJS.ProcessEnv) {
  return { client_id: configured(env, 'TIKTOK_BUSINESS_APP_ID'), client_secret: configured(env, 'TIKTOK_BUSINESS_APP_SECRET') };
}

function credential(body: Record<string, unknown>, previous?: Credential): Credential {
  const openId = identity(body.open_id);
  if (previous?.fields?.openId && openId !== previous.fields.openId) throw new ProviderError('TikTok returned a different account while refreshing. Reconnect the account holder.', 502);
  if (typeof body.expires_in !== 'number' || !Number.isFinite(body.expires_in) || body.expires_in <= 0 ||
      typeof body.scope !== 'string' || body.scope.length > 8192) throw new ProviderError(`${label} returned an invalid token response.`, 502);
  const result = tokenResponse(body, previous);
  safeCredential(result);
  return { ...result, fields: { openId, scope: body.scope } };
}

/** Companion authorization only; it must never supply tokens to advertiser or Login Kit actions. */
export const tiktokAccountAdapter: ProviderAdapter = {
  definition: {
    id: 'tiktok-business-account', name: 'TikTok account holder', category: 'advertising', authType: 'oauth',
    auxiliaryFor: 'tiktok-business',
    description: 'Authorize and verify a TikTok account through the API for Business Accounts API.', docsUrl,
  },
  requiredEnv: ['TIKTOK_BUSINESS_APP_ID', 'TIKTOK_BUSINESS_APP_SECRET', 'TIKTOK_BUSINESS_ACCOUNT_AUTH_URL'],
  authorize({ redirectUri, state, env }) {
    const url = authorizationUrl(env, redirectUri);
    url.searchParams.set('state', state);
    url.searchParams.set('disable_auto_auth', '1');
    return url.toString();
  },
  async exchange({ code, redirectUri, env }) {
    // Recheck the saved URL before sending a one-time code with these credentials.
    authorizationUrl(env, redirectUri);
    return credential(await post('tt_user/oauth2/token/', {
      ...appCredentials(env), grant_type: 'authorization_code', auth_code: code, redirect_uri: redirectUri,
    }));
  },
  async refresh(previous, env) {
    if (!previous.refreshToken) throw new ProviderError('TikTok account-holder access has expired. Reconnect the account holder.', 401);
    return credential(await post('tt_user/oauth2/refresh_token/', {
      ...appCredentials(env), grant_type: 'refresh_token', refresh_token: previous.refreshToken,
    }), previous);
  },
  async verify(token, env) {
    const result = await post('tt_user/token_info/get/', {
      app_id: configured(env, 'TIKTOK_BUSINESS_APP_ID'), access_token: safeCredential(token),
    });
    const accountId = identity(result.creator_id);
    if (result.app_id !== configured(env, 'TIKTOK_BUSINESS_APP_ID') || accountId !== token.fields?.openId || typeof result.scope !== 'string') {
      throw new ProviderError('TikTok account-holder verification did not match the authorized app and account. Reconnect the account holder.', 502);
    }
    const accountName = `TikTok account ${accountId}`;
    return { accountId, accountName, resources: [{ id: accountId, name: accountName, type: 'tiktok_account' }] };
  },
};
